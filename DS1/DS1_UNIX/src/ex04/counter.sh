#!/bin/sh

# 1. Записываем заголовок
echo '"name","count"' > hh_uniq_positions.csv

# 2. Пайплайн обработки:
# tail -n +2: пропускаем заголовок исходного файла (из ex03!)
# cut -d',' -f3: берем 3-ю колонку (название позиции)
# tr -d '"': удаляем лишние кавычки
# sort: СОРТИРУЕМ ПО АЛФАВИТУ (обязательно для работы uniq!)
# uniq -c: считаем количество одинаковых строк подряд
# sort -rn: сортируем по количеству (числовая, по убыванию)
# sed: форматируем обратно в CSV "name",count
tail -n +2 ../ex03/hh_positions.csv | \
  cut -d',' -f3 | \
  tr -d '"' | \
  sort | \
  uniq -c | \
  sort -rn | \
  sed -E 's/^ *([0-9]+) (.+)$/"\2",\1/' >> hh_uniq_positions.csv
